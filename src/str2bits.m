function bits = str2bits(msg)

    %STR2BITS Преобразует строку символов в поток бит (MSB первым, 8 бит на символ)
    asciiVals = double(msg);
    bitsMatrix = dec2bin(asciiVals, 8) - '0'; % Получили численные значения, вычтя '0' из символов '0' и '1', чтобы получить 0 и 1

    % Преобразуем матрицу бит в одномерный массив битов (транспонируем, и склеиваем столбцы, сначала первый, затем второй и т.д.)
    bits = reshape(bitsMatrix.', 1, []); % .' операция транспонирования 
end